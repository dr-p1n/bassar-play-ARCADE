#!/usr/bin/env python3
"""
BASSAR — build step.

Takes the one canonical client in client/bassar-client.js and puts it where it
has to live:

  <games>/<slug>.html inlined, self-contained, uploadable to itch.io
                      (the folder is "bassar play/"; see GAME_DIR_NAMES)
  site/games/         the same files, served by the arcade
  site/bassar.js        the site variant (no game, site-only helpers kept)

It also makes sure each game has the two bits of markup the client needs:
a #returnLine on the title screen and a share block on the end screen.

Run it after ANY edit to the client. Editing the copy inside a game is how
three copies quietly stop agreeing with each other.

    python3 build.py
"""
import pathlib, re, sys

ROOT   = pathlib.Path(__file__).parent
CLIENT = (ROOT / "client" / "bassar-client.js").read_text(encoding="utf-8")

# The standalone (itch.io) copies. The folder has been renamed more than once,
# and a rename silently breaks the build, so resolve it by looking for the file
# rather than by trusting a name: any directory holding the game slugs wins.
# Where the site will actually be served. og:image and og:url must be absolute
# URLs — Facebook and X will not resolve a relative one — so this is the single
# place a host is named, in the same spirit as BASSAR_SITE in the client.
# Empty means "skip the absolute tags", which is right for local work.
# CHANGE THIS AT MIGRATION, then rerun the build. See DEPLOY.md.
OG_BASE = "https://bassarplay.com"

GAME_DIR_NAMES = ("bassar play", "ARCADE", "games")

def find_arcade() -> pathlib.Path:
    for n in GAME_DIR_NAMES:
        if (ROOT / n).is_dir():
            return ROOT / n
    # last resort: any single-level directory containing the games
    for d in sorted(p for p in ROOT.iterdir() if p.is_dir() and not p.name.startswith(".")):
        if all((d / f"{g}.html").exists() for g in ("void-drift", "transcript")):
            return d
    return ROOT / GAME_DIR_NAMES[0]

ARCADE = find_arcade()
SITE   = ROOT / "site"

# STAGING BUILD:  python3 build.py --staging [--endpoint URL]
# Builds a copy into .staging/ with the capture endpoint pointed at the staging
# worker. site/ and the standalone (itch.io) games are never touched, so a
# staging build cannot be deployed to bassarplay.com by accident.
STAGING = "--staging" in sys.argv
STAGING_ENDPOINT = "https://bassar-capture-staging.julioernestolv.workers.dev"
if STAGING:
    import shutil
    if "--endpoint" in sys.argv:
        STAGING_ENDPOINT = sys.argv[sys.argv.index("--endpoint") + 1].rstrip("/")
    OUT = ROOT / ".staging"
    shutil.rmtree(OUT, ignore_errors=True)
    shutil.copytree(SITE, OUT / "site")
    shutil.copytree(ARCADE, OUT / "games-src")
    SITE, ARCADE = OUT / "site", OUT / "games-src"
    OG_BASE = ""      # no absolute share tags on a staging host

BEGIN = "/* ==== BASSAR CLIENT — generated by build.py. Edit client/bassar-client.js. ==== */"
END   = "/* ==== END BASSAR CLIENT ==== */"

# the in-world line each game shows someone who has been here before.
# %N% becomes "once" or "N times".
GAMES = {
  "void-drift":
    "You have run this build before — %N%. The log remembers what you recovered.",
  "recovered-records":
    "You have walked this site before — %N%. It walked back.",
  "transcript":
    "You have opened this channel before — %N%. It has been waiting at the same interval.",
}

# One id per build run, stamped into every copy of the client as BASSAR_BUILD so an
# error report can be tied to the deploy that shipped it. Staging builds say so.
import datetime, hashlib
BUILD_ID = ("staging-" if "--staging" in sys.argv else "") + \
    datetime.datetime.now(datetime.timezone.utc).strftime("%Y%m%d-%H%M") + "-" + \
    hashlib.sha1(CLIENT.encode("utf-8")).hexdigest()[:7]

SITE_ONLY = re.compile(r"/\* ==== SITE ONLY ====.*?/\* ==== /SITE ONLY ==== \*/\n?", re.S)

# the client block as it currently sits in a game: either a previous build's
# marked region, or the first hand-wired version
REGION = re.compile(
    r"(?:" + re.escape(BEGIN) + r".*?" + re.escape(END) + r")"
    r"|(?:/\* -+ bassar capture .*?\n\}\)\(\);)",
    re.S)

RETURN_LINE = '    <div id="returnLine" class="dim" style="display:none;margin:.6em 0"></div>\n'

SHARE_BLOCK = """    <div class="rule"></div>
    <div class="tag">PASS IT ON</div>
    <div class="dim">Anyone who walks in on your line arrives marked as yours.</div>
    <input id="shareIn" type="text" readonly>
    <button id="shareB">COPY THE LINK</button>
"""

# strip any previous insertion so the block can be re-placed, not duplicated
SHARE_RE = re.compile(
    r' *<div class="rule"></div>\n *<div class="tag">PASS IT ON</div>\n'
    r' *<div class="dim">Anyone who walks in on your line[^\n]*\n'
    r' *<input id="shareIn"[^\n]*\n *<button id="shareB">[^\n]*\n')

# the share control belongs after the signup form, before the play-again
# button — offering someone a link to pass on before they have filed
# themselves puts the two calls to action in the wrong order
AGAIN_RE = re.compile(r'(\n *<button id="again[2B]")')


def client_for(game: str, return_line: str, site: bool) -> str:
    src = CLIENT
    if STAGING:
        src = re.sub(r'(const BASSAR_ENDPOINT = ")[^"]*(")', lambda m: m.group(1) + STAGING_ENDPOINT + m.group(2), src, count=1)
    if not site:
        src = SITE_ONLY.sub("", src)
    src = src.replace('const BASSAR_BUILD    = "%BUILD%";',
                      f'const BASSAR_BUILD    = "{BUILD_ID}";')
    src = src.replace('const BASSAR_GAME     = "%GAME%";',
                      f'const BASSAR_GAME     = "{game}";')
    src = src.replace('const BASSAR_RETURN   = "%RETURN%";',
                      f'const BASSAR_RETURN   = "{return_line}";')
    return src


def build_game(path: pathlib.Path, slug: str) -> bool:
    s = orig = path.read_text(encoding="utf-8")
    ok = True

    # 1. the client
    block = BEGIN + "\n" + client_for(slug, GAMES[slug], site=False).rstrip() + "\n" + END
    if not REGION.search(s):
        print(f"!! {path.name}: no client region found"); return False
    s = REGION.sub(lambda m: block, s, count=1)

    # 2. the in-world return line, on the title panel under the <h1>
    if 'id="returnLine"' not in s:
        m = re.search(r'( *<h1>.*?</h1>\n)', s)
        if not m:
            print(f"!! {path.name}: no <h1> to anchor the return line to"); ok = False
        else:
            s = s[:m.end(1)] + RETURN_LINE + s[m.end(1):]

    # 3. the share block, after the signup form on the end screen
    s = SHARE_RE.sub("", s)
    m = AGAIN_RE.search(s)
    if not m:
        print(f"!! {path.name}: no play-again button to anchor the share block to"); ok = False
    else:
        s = s[:m.start(1)] + "\n" + SHARE_BLOCK.rstrip("\n") + s[m.start(1):]

    # 4. greet on load, wire the share control when a run ends
    if "BASSAR.greet();" not in s:
        for old, new in [
            ('document.getElementById("startB").addEventListener("click",begin);',
             'document.getElementById("startB").addEventListener("click",begin);\nBASSAR.greet();'),
        ]:
            if old in s: s = s.replace(old, new, 1); break
        else:
            print(f"!! {path.name}: nowhere to call BASSAR.greet()"); ok = False

    # look for the CALL, not the definition — the client (which defines it)
    # is inlined above, so a bare "bassarBindShare(" always matches
    if f'bassarBindShare("{slug}")' not in s:
        m = re.search(r'(function end\(kind,sub\)\{|function die\(\)\{)', s)
        if not m:
            print(f"!! {path.name}: no end/die function to hook the share block into"); ok = False
        else:
            s = s[:m.end(1)] + '\n  bassarBindShare("' + slug + '");' + s[m.end(1):]

    if s != orig:
        path.write_text(s, encoding="utf-8")
    print(("ok  " if ok else "!!  ") + f"{path.name}  ({len(orig)} -> {len(s)} bytes)")
    return ok


PAGE_RETURN = '    <p id="returnLine" class="dim" style="display:none;margin:.9em 0 0"></p>\n'


def build_page(path: pathlib.Path) -> bool:
    """Make sure a shell page has the return line and calls the greeter.
    Someone arriving on a share link lands here, and should be told so."""
    if not path.exists():
        print(f"!! missing {path}"); return False
    s = orig = path.read_text(encoding="utf-8")

    if 'id="returnLine"' not in s:
        m = re.search(r'( *</nav>\n)', s)
        if not m:
            print(f"!! {path.parent.name}/index.html: no </nav> to anchor to"); return False
        s = s[:m.end(1)] + PAGE_RETURN + s[m.end(1):]

    if "bassarGreetPage()" not in s:
        if "bassarBindForms();" not in s:
            print(f"!! {path.parent.name}/index.html: no script block to extend"); return False
        s = s.replace("bassarBindForms();", "bassarBindForms();\n  bassarGreetPage();", 1)

    if s != orig:
        path.write_text(s, encoding="utf-8")
    print(f"ok  {path.parent.name}/{path.name}")
    return True


HEAD_BEGIN = "<!-- ==== BASSAR HEAD — generated by build.py ==== -->"
HEAD_END   = "<!-- ==== /BASSAR HEAD ==== -->"
HEAD_RE = re.compile(re.escape(HEAD_BEGIN) + r".*?" + re.escape(HEAD_END) + r"\n?", re.S)


def build_head(path: pathlib.Path, url_path: str) -> bool:
    """The favicon, and the share-card tags. Every page gets them: a link into
    a game travels as often as a link to the front page, and a share with no
    preview image is the referral mechanic losing a fight it never saw."""
    if not path.exists():
        print(f"!! missing {path}"); return False
    s = orig = path.read_text(encoding="utf-8")
    s = HEAD_RE.sub("", s)

    lines = [HEAD_BEGIN, '<link rel="icon" href="/favicon.svg" type="image/svg+xml">']
    if OG_BASE:
        base = OG_BASE.rstrip("/")
        lines += [f'<meta property="og:image" content="{base}/og.png">',
                  f'<meta property="og:url" content="{base}{url_path}">',
                  '<meta name="twitter:card" content="summary_large_image">']
    lines.append(HEAD_END)
    injected = "\n".join(lines) + "\n"

    anchor = '<link rel="stylesheet" href="/bassar.css">'
    if anchor not in s:
        print(f"!! {path.parent.name}/{path.name}: no stylesheet link to anchor the head to")
        return False
    s = s.replace(anchor, injected + anchor, 1)

    if s != orig:
        path.write_text(s, encoding="utf-8")
    print(f"ok  {path.parent.name}/{path.name}  head"
          + ("" if OG_BASE else "  (OG_BASE empty — favicon only)"))
    return True


NAV_BEGIN = "<!-- ==== BASSAR NAV ==== -->"
NAV_END   = "<!-- ==== /BASSAR NAV ==== -->"
NAV_RE    = re.compile(re.escape(NAV_BEGIN) + r".*?" + re.escape(NAV_END), re.S)
NAV_ITEMS = [("GAMES", "/games/"), ("THE RECORD", "/record/"), ("CONTACT", "/contact/")]


def build_nav(path: pathlib.Path, current: str) -> bool:
    """The site nav, GAMES · THE RECORD · CONTACT, on every page. Pages carry an empty
    marked region; this fills it, so a new item is one edit here, not six."""
    if not path.exists():
        print(f"!! missing {path}"); return False
    s = orig = path.read_text(encoding="utf-8")
    if not NAV_RE.search(s):
        print(f"!! {path.parent.name}/{path.name}: no nav region (add the two BASSAR NAV comments)"); return False
    links = "".join(
        f'<a href="{href}"' + (' aria-current="page"' if label == current else "") + f">{label}</a>"
        for label, href in NAV_ITEMS)
    s = NAV_RE.sub(lambda m: NAV_BEGIN + f'\n<nav class="sitenav" aria-label="Site">{links}</nav>\n' + NAV_END, s, count=1)
    if s != orig:
        path.write_text(s, encoding="utf-8")
    print(f"ok  {path.parent.name}/{path.name}  nav ({current})")
    return True


def main() -> int:
    ok = True
    for slug in GAMES:
        p = ARCADE / f"{slug}.html"
        if not p.exists():
            print(f"!! missing {p}")
            print(f"   the standalone games directory did not resolve. Looked for "
                  f"{', '.join(GAME_DIR_NAMES)} under {ROOT}. If it was renamed, "
                  f"add the new name to GAME_DIR_NAMES.")
            ok = False; continue
        ok &= build_game(p, slug)
        # the arcade serves its own copy; keep them byte-identical
        dst = SITE / "games" / f"{slug}.html"
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_text(p.read_text(encoding="utf-8"), encoding="utf-8")

    for slug in GAMES:
        ok &= build_page(SITE / slug / "index.html")

    ok &= build_head(SITE / "index.html", "/")
    for slug in GAMES:
        ok &= build_head(SITE / slug / "index.html", f"/{slug}/")

    # the site nav on every page; GAMES is current on the games page and on each game, nothing on the landing
    ok &= build_nav(SITE / "index.html", "")
    for slug in GAMES:
        ok &= build_nav(SITE / slug / "index.html", "GAMES")
    ok &= build_nav(SITE / "games" / "index.html", "GAMES")
    ok &= build_head(SITE / "games" / "index.html", "/games/")
    ok &= build_nav(SITE / "record" / "index.html", "THE RECORD")
    ok &= build_nav(SITE / "contact" / "index.html", "CONTACT")
    ok &= build_head(SITE / "contact" / "index.html", "/contact/")

    # THE RECORD (leaderboard): reads the capture API, so a staging build points it at staging too
    rec = SITE / "record" / "index.html"
    ok &= build_head(rec, "/record/")
    if STAGING and rec.exists():
        t = re.sub(r'(var BOARD_API = ")[^"]*(")', lambda m: m.group(1) + STAGING_ENDPOINT + m.group(2), rec.read_text(encoding="utf-8"), count=1)
        rec.write_text(t, encoding="utf-8")

    site_js = SITE / "bassar.js"
    site_js.write_text(client_for("", "", site=True), encoding="utf-8")
    print(f"ok  {site_js.relative_to(ROOT)}  ({len(site_js.read_text())} bytes)")
    if STAGING:
        print(f"\nSTAGING build in {OUT.relative_to(ROOT)}/site  ->  endpoint {STAGING_ENDPOINT}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
